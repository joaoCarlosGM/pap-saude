const status = 'Registro sintético salvo no laboratório privado.'
const button = (scope: Page | Locator,name: string) => scope.getByRole('button',{name,exact:true})
const tab = (page:Page,name:string) => button(page,name).click()
const entry = (page:Page,name:string) => page.getByRole('article',{name,exact:true})
const field = (form:Locator,name:string) => form.getByLabel(name,{exact:true})
const api = (path:string) => path.replace('/vitrine/','/homologacao/')+'/prontuario'
async function authorize(page:Page) {
  await page.goto('/vitrine/configuracoes')
  await page.locator('[data-demo-ready=true]').waitFor({state:'attached'})
  const details = page.locator('[data-private-review]>summary')
  await details.click()
  await button(page,'Autorizar consulta local dos PDFs').click()
  await expect(details).toContainText('consulta autorizada')
}
async function draft(page:Page,action:string,scope:Page|Locator=page) {
  await button(scope,action).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  return dialog
}
async function saved(page:Page, form:Locator) {
  await button(form,'Salvar registro').click()
  await expect(form).toBeHidden()
  await expect(page.getByText(status,{exact:true})).toBeVisible()
}
async function source(form:Locator,value='relato') {
  await field(form,'Origem da informação').selectOption(value)
}
async function choose(form:Locator,value:string) {await field(form,'Situação').selectOption(value)}
async function viewport(page:Page,width:number) {
  await page.setViewportSize({width,height:width<=430?820:900})
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
}
