for(const [index,slug] of ['sindromes-hipertensivas-gestacao','hemorragia-pos-parto','sepse-obstetrica'].entries()) {
  test(`H42 progressive graph ${slug} preserves all frames and reduced motion`,async({page})=>{
    test.setTimeout(90000)
    await page.setViewportSize({width:1440,height:1000})
    await page.goto('/vitrine/protocolos?protocolo='+slug+'&aba=fluxograma')
    const map=page.getByRole('region',{name:'Mapa navegável do fluxograma'})
    const total=Number(await map.getAttribute('data-flow-total'))
    expect(total).toBeGreaterThan(20)
    await page.getByRole('button',{name:'Reiniciar',exact:true}).click()
    await expect(map).toHaveAttribute('data-flow-frame','0')
    if (evidence) await map.screenshot({path:`${evidence}/protocolo-${index+1}-0.png`})
    await page.getByRole('button',{name:'Continuar',exact:true}).click()
    for(const percent of [25,50,75,100]) {
      await expect.poll(async()=>Number(await map.getAttribute('data-flow-frame')),{timeout:15000}).toBeGreaterThanOrEqual(Math.ceil(total*percent/100))
      if (evidence) {
        await map.evaluate((element,position)=>{
          element.scrollTop=(element.scrollHeight-element.clientHeight)*Math.max(0,(position-25)/75)
        },percent)
        await map.screenshot({path:`${evidence}/protocolo-${index+1}-${percent}.png`,animations:'disabled'})
      }
    }
    expect((await map.locator('[data-flow-node]').count())+(await map.locator('[data-flow-edge]').count())).toBe(total)
    expect(await map.locator('[data-flow-node]').evaluateAll(cards=>cards.every(card=>card.scrollHeight<=card.clientHeight+1))).toBe(true)
    await page.getByRole('button',{name:'Reproduzir',exact:true}).click()
    await expect.poll(async()=>Number(await map.getAttribute('data-flow-frame'))).toBeGreaterThan(0)
    await page.getByRole('button',{name:'Pausar',exact:true}).click()
    const paused=await map.getAttribute('data-flow-frame')
    await expect(page.locator('[data-flow-status]')).toHaveAttribute('data-flow-status','paused')
    await expect(map).toHaveAttribute('data-flow-frame',paused!)
    await page.getByRole('button',{name:'Ver completo',exact:true}).click()
    await expect(map).toHaveAttribute('data-flow-frame',String(total))
    await page.setViewportSize({width:390,height:900})
    await page.emulateMedia({reducedMotion:'reduce'})
    await expect(page.getByRole('button',{name:'Reiniciar',exact:true})).toBeDisabled()
    await expect(map.locator('[data-flow-node]').first()).toBeVisible()
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  })
}

