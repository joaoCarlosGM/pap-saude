import {test, expect, devices, type Page} from '@playwright/test'

test.use({...devices['Pixel 7'], defaultBrowserType:'chromium'})

test.beforeEach(async ({page}) => {
  await page.addInitScript(() => sessionStorage.setItem('pap.vitrine.premium.welcome.v2','seen'))
  await page.emulateMedia({reducedMotion:'reduce'})
})

async function navigate(page: Page, label: string, path: string) {
  await page.getByRole('button', {name:'Abrir menu', exact:true}).click()
  await page.getByRole('navigation', {name:'Módulos'}).getByRole('link', {name:label, exact:true}).click()
  await expect(page).toHaveURL(new RegExp(path + '$'))
}

