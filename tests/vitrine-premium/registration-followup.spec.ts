test('agenda persiste, mostra lembrete, preserva mudanças e atualiza o prontuário', async ({page}) => {
  test.setTimeout(120_000)
  await page.goto('/vitrine/agenda')
  await page.locator('[data-demo-ready=true]').waitFor({state:'attached'})
  const patient = 'Maria das Graças Silva'
  await page.getByRole('button',{name:'Novo compromisso'}).click()
  const form = page.locator('form').filter({has:page.getByRole('button',{name:'Salvar compromisso'})})
  await form.getByRole('combobox',{name:'Paciente',exact:true}).selectOption({label:patient})
  await form.getByRole('combobox',{name:'Tipo de compromisso'}).selectOption('solicitacao')
  await form.getByLabel('Motivo').fill('Exame sintético de acompanhamento')
  await form.getByRole('button',{name:'Salvar compromisso'}).click()
  await expect(page.getByText('Compromisso salvo.',{exact:true})).toBeVisible()

  await page.reload()
  const item = page.getByRole('article').filter({hasText:'Exame sintético de acompanhamento'})
  await expect(item.getByText('Sem data agendada',{exact:true})).toBeVisible()
  await item.getByRole('button',{name:'Agendar exame'}).click()
  const future = new Date(Date.now() + (2 - 3) * 3_600_000).toISOString()
  await item.getByLabel('Data',{exact:true}).fill(future.slice(0,10))
  await item.getByLabel('Horário (Fortaleza)').fill(future.slice(11,16))
  await item.getByRole('button',{name:'Salvar nova data'}).click()
  await expect(item.getByRole('heading',{name:'Exame',exact:true})).toBeVisible()
  await item.getByRole('combobox',{name:'Nova situação'}).selectOption('confirmado')
  await item.getByRole('button',{name:'Atualizar situação'}).click()
  await expect(item.getByText('Confirmado',{exact:true})).toBeVisible()

  await page.getByRole('button',{name:'Abrir menu',exact:true}).click()
  await page.getByRole('button',{name:'Avisos',exact:true}).click()
  const inbox = page.getByRole('dialog',{name:'Caixa de entrada'})
  await inbox.getByRole('button',{name:'Agenda',exact:true}).click()
  await expect(inbox.getByRole('heading',{name:'Lembrete de exame'})).toBeVisible()
  await inbox.getByRole('button',{name:'Fechar',exact:true}).click()

  await item.getByRole('link',{name:patient,exact:true}).click()
  await expect(page.getByRole('heading',{name:'Próximos compromissos'})).toBeVisible()
  await expect(page.getByText(/^Exame ·/)).toBeVisible()
  await page.getByRole('button',{name:'Abrir agenda da paciente'}).click()
  const inChart = page.getByRole('article').filter({hasText:'Exame sintético de acompanhamento'})
  await inChart.getByRole('combobox',{name:'Nova situação'}).selectOption('cancelado')
  await inChart.getByRole('button',{name:'Atualizar situação'}).click()
  await inChart.getByText('Histórico do compromisso',{exact:true}).click()
  await expect(inChart.getByText(/Registro criado · Planejado · Sem data agendada/)).toBeVisible()
  await expect(inChart.getByText(/Situação atualizada · Cancelado/)).toBeVisible()
  await navigate(page,'Agenda','/vitrine/agenda')
  await expect(item.getByText('Cancelado',{exact:true})).toBeVisible()
})
